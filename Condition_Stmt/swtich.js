// 6. Switch Statement
switch(add)
{
    case 1:
        console.log("number = 1")
        break;
    case 2:
       console.log("number = 2")
    case 3:
       console.log("number = 3")
    case add:
        console.log("number = 4")
    default:
       console.log("no other option")
}

